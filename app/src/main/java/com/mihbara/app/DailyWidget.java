    static int dayIndex() {
        Calendar c = Calendar.getInstance();
        return c.get(Calendar.DAY_OF_YEAR) + c.get(Calendar.YEAR) * 400;
    }

    @Override
    public void onUpdate(Context ctx, AppWidgetManager mgr, int[] ids) {
        for (int id : ids) update(ctx, mgr, id);
    }

    @Override
    public void onReceive(Context ctx, Intent intent) {
        super.onReceive(ctx, intent);
        String a = intent.getAction();
        if (Intent.ACTION_DATE_CHANGED.equals(a) || Intent.ACTION_TIME_CHANGED.equals(a) || Intent.ACTION_TIMEZONE_CHANGED.equals(a)) {
            AppWidgetManager mgr = AppWidgetManager.getInstance(ctx);
            onUpdate(ctx, mgr, mgr.getAppWidgetIds(new ComponentName(ctx, DailyWidget.class)));
        }
    }

    static void update(Context ctx, AppWidgetManager mgr, int id) {
        int i = dayIndex();
        String[] t = TERMS[i % TERMS.length];
        String[] s = SENT[i % SENT.length];
        RemoteViews v = new RemoteViews(ctx.getPackageName(), R.layout.widget_daily);
        v.setTextViewText(R.id.w_term, t[0]);
        v.setTextViewText(R.id.w_en, t[1]);
        v.setTextViewText(R.id.w_def, t[2]);
        v.setTextViewText(R.id.w_wrong, "✗ " + s[0]);
        v.setTextViewText(R.id.w_right, "✓ " + s[1]);
        Intent open = new Intent(ctx, MainActivity.class);
        open.setFlags(Intent.FLAG_ACTIVITY_NEW_TASK | Intent.FLAG_ACTIVITY_CLEAR_TOP);
        PendingIntent pi = PendingIntent.getActivity(ctx, 0, open, PendingIntent.FLAG_UPDATE_CURRENT | PendingIntent.FLAG_IMMUTABLE);
        v.setOnClickPendingIntent(R.id.w_root, pi);
        mgr.updateAppWidget(id, v);
    }
